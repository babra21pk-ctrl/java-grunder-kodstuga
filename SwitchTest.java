public class SwitchTest {
    public static void main(String[] args) {

        int option = 2;

        switch (option) {
            case 1:
                System.out.println("Kaffe");
                break;

            case 2:
                System.out.println("Te");
                break;

            case 3:
                System.out.println("Juice");
                break;

            default:
                System.out.println("Ogiltigt alternativ.");
        }
    }
} 
    

