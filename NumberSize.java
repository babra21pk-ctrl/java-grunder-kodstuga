public class NumberSize {
    public static void main(String[] args) {

        int number = 70;

        if (number <= 20) {
            System.out.println("Talet är litet.");
        } else if (number <= 50) {
            System.out.println("Talet är mellan.");
        } else {
            System.out.println("Talet är stort.");
        }
    }
}
